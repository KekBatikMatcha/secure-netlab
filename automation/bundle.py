"""Config bundles: one device's named config sections, plus a stable text form for storage.

Text form (what is stored in backups/ and golden/):

    ### section firewall
    <section text>
    ### section listeners
    <section text>
"""

from __future__ import annotations

import re
from dataclasses import dataclass

SECTION_PREFIX = "### section "

# iptables-save prints per-chain packet counters like "[12:720]". They change on every
# poll, so they are removed before comparing or storing.
_COUNTERS = re.compile(r"\s*\[\d+:\d+\]")
# Loopback listeners are not exposure. Docker's embedded DNS (127.0.0.11) picks a new random
# port on every container start, so it would look like drift if we kept it.
_LOOPBACK = re.compile(r"\s(127\.\d+\.\d+\.\d+|\[?::1\]?):\d+")


def normalize_section(name: str, text: str) -> str:
    """Return a stable form of one section so that only real config changes show up."""
    lines = [line.strip() for line in text.splitlines()]
    if name == "firewall":
        # Drop comments (including "# Generated by ... <timestamp>") and blank lines.
        kept = [_COUNTERS.sub("", line) for line in lines if line and not line.startswith("#")]
    elif name == "listeners":
        # Keep externally reachable listening sockets. Sort so re-ordering alone is not drift.
        kept = sorted(
            " ".join(line.split())
            for line in lines
            if "LISTEN" in line and not _LOOPBACK.search(line)
        )
    else:
        kept = [line for line in lines if line]
    return "\n".join(kept)


@dataclass(frozen=True)
class ConfigBundle:
    sections: dict[str, str]

    def normalized(self) -> ConfigBundle:
        return ConfigBundle(
            {name: normalize_section(name, text) for name, text in self.sections.items()}
        )

    def to_text(self) -> str:
        parts = [
            f"{SECTION_PREFIX}{name}\n{self.sections[name].rstrip()}\n"
            for name in sorted(self.sections)
        ]
        return "".join(parts)

    @classmethod
    def from_text(cls, text: str) -> ConfigBundle:
        sections: dict[str, str] = {}
        current: str | None = None
        buffer: list[str] = []
        for line in text.splitlines():
            if line.startswith(SECTION_PREFIX):
                if current is not None:
                    sections[current] = "\n".join(buffer)
                current = line[len(SECTION_PREFIX) :].strip()
                buffer = []
            elif current is not None:
                buffer.append(line)
        if current is not None:
            sections[current] = "\n".join(buffer)
        return cls(sections)
