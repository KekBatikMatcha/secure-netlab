"""Normalization and drift detection, using the sample router configs in tests/fixtures."""

from __future__ import annotations

from pathlib import Path

from automation.bundle import ConfigBundle, normalize_section
from automation.drift import compare

FIXTURES = Path(__file__).parent / "fixtures"


def load(name: str) -> ConfigBundle:
    return ConfigBundle.from_text((FIXTURES / name).read_text(encoding="utf-8"))


def summary(report) -> list[tuple[str, str]]:  # type: ignore[no-untyped-def]
    return sorted((f.kind, f.severity) for f in report.findings)


def with_listeners(bundle: ConfigBundle, *lines: str) -> ConfigBundle:
    sections = dict(bundle.sections)
    sections["listeners"] = sections["listeners"] + "\n" + "\n".join(lines)
    return ConfigBundle(sections)


def with_firewall(bundle: ConfigBundle, text: str) -> ConfigBundle:
    sections = dict(bundle.sections)
    sections["firewall"] = text
    return ConfigBundle(sections)


# --- normalisation -------------------------------------------------------------------------


def test_normalize_firewall_strips_counters_and_comments() -> None:
    raw = "# Generated by iptables-save on Sat\n:FORWARD DROP [5:600]\n-A FORWARD -j ACCEPT [1:2]"
    assert normalize_section("firewall", raw) == ":FORWARD DROP\n-A FORWARD -j ACCEPT"


def test_normalize_listeners_keeps_only_listening_sockets_sorted() -> None:
    raw = (
        "Proto Recv-Q Send-Q Local Address Foreign Address State\n"
        "tcp 0 0 0.0.0.0:502 0.0.0.0:* LISTEN\n"
        "tcp 0 0 0.0.0.0:22 0.0.0.0:* LISTEN\n"
        "tcp 0 0 10.0.0.1:5000 10.0.0.2:40000 ESTABLISHED\n"
    )
    assert normalize_section("listeners", raw) == (
        "tcp 0 0 0.0.0.0:22 0.0.0.0:* LISTEN\ntcp 0 0 0.0.0.0:502 0.0.0.0:* LISTEN"
    )


def test_loopback_listeners_are_ignored() -> None:
    # Docker DNS on 127.0.0.11 gets a new random port on each start: must not count as drift.
    raw = (
        "tcp 0 0 127.0.0.11:44603 0.0.0.0:* LISTEN\n"
        "tcp 0 0 127.0.0.1:631 0.0.0.0:* LISTEN\n"
        "tcp 0 0 [::1]:8000 [::]:* LISTEN\n"
        "tcp 0 0 0.0.0.0:502 0.0.0.0:* LISTEN"
    )
    assert normalize_section("listeners", raw) == "tcp 0 0 0.0.0.0:502 0.0.0.0:* LISTEN"


def test_normalized_bundle_survives_store_round_trip() -> None:
    normalized = load("router_baseline.cfg").normalized()
    assert ConfigBundle.from_text(normalized.to_text()) == normalized


# --- drift ---------------------------------------------------------------------------------


def test_counter_and_timestamp_changes_are_not_drift() -> None:
    report = compare("router", load("router_baseline.cfg"), load("router_counters_only.cfg"))
    assert not report.has_drift
    assert report.to_text() == "OK router: no drift"


def test_drift_case_finds_changed_rule_new_management_rule_and_new_listener() -> None:
    report = compare("router", load("router_baseline.cfg"), load("router_drift.cfg"))
    assert summary(report) == [
        ("firewall-rule-added", "high"),  # new allow on management port 22
        ("firewall-rule-changed", "medium"),  # 8080 -> 8443 on the user->server rule
        ("listener-added", "high"),  # telnet (23) now listening
    ]
    by_kind = {f.kind: f.detail for f in report.findings}
    assert "--dport 8080" in by_kind["firewall-rule-changed"]
    assert "--dport 8443" in by_kind["firewall-rule-changed"]
    assert "--dport 22" in by_kind["firewall-rule-added"]
    assert "tcp/23" in by_kind["listener-added"]


def test_drift_report_text_shows_count_and_severity() -> None:
    text = compare("router", load("router_baseline.cfg"), load("router_drift.cfg")).to_text()
    assert text.startswith("DRIFT router: 3 finding(s)")
    assert "[HIGH] listener-added" in text


def test_policy_change_is_high_severity() -> None:
    base = load("router_baseline.cfg")
    changed = with_firewall(
        base, base.sections["firewall"].replace(":FORWARD DROP", ":FORWARD ACCEPT")
    )
    report = compare("router", base, changed)
    assert summary(report) == [("policy-changed", "high")]
    assert "FORWARD: DROP -> ACCEPT" in report.findings[0].detail


def test_removed_rule_without_replacement_is_medium() -> None:
    base = load("router_baseline.cfg")
    text = "\n".join(
        line
        for line in base.sections["firewall"].splitlines()
        if "--dport 502" not in line
    )
    report = compare("router", base, with_firewall(base, text))
    assert summary(report) == [("firewall-rule-removed", "medium")]


def test_new_listener_on_non_management_port_is_medium() -> None:
    base = load("router_baseline.cfg")
    current = with_listeners(base, "tcp 0 0 0.0.0.0:8080 0.0.0.0:* LISTEN")
    assert summary(compare("router", base, current)) == [("listener-added", "medium")]


def test_closed_management_port_is_low() -> None:
    base = load("router_baseline.cfg")
    baseline_with_ssh = with_listeners(base, "tcp 0 0 0.0.0.0:22 0.0.0.0:* LISTEN")
    assert summary(compare("router", baseline_with_ssh, base)) == [("listener-removed", "low")]


def test_missing_section_is_reported_and_other_sections_still_compared() -> None:
    base = load("router_baseline.cfg")
    current = ConfigBundle({"firewall": base.sections["firewall"]})
    assert summary(compare("router", base, current)) == [("section-missing", "medium")]
